# Дано целое число N, а также действительные числа A и B. Сформировать массив из N первых членов арифметической прогрессии с первым членом A и разностью B.
n = int(input("Введите количество элементов массива: "))
a, b = map(float, input("Введите A и B через пробел: ").split())

array = [a - i * b for i in range(n)]

print(*array)