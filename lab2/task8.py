# Дано целое число в диапазоне 1–99, определяющее количество учебных заданий. Вывести строку-описание указанного числа вида «двадцать одно учебное задание», «тридцать два учебных задания» и т. д.
number = int(input("Введите количество учебных заданий: "))

ones = {
	0: "",
	1: "один",
	2: "два",
	3: "три",
	4: "четыре",
	5: "пять",
	6: "шесть",
	7: "семь",
	8: "восемь",
	9: "девять",
}
teens = {
	10: "десять", 11: "одиннадцать", 12: "двенадцать", 13: "тринадцать",
	14: "четырнадцать", 15: "пятнадцать", 16: "шестнадцать",
	17: "семнадцать", 18: "восемнадцать", 19: "девятнадцать",
}
tens = {
	2: "двадцать",
	3: "тридцать",
	4: "сорок",
	5: "пятьдесят",
	6: "шестьдесят",
	7: "семьдесят",
	8: "восемьдесят",
	9: "девяносто",
}

if number < 20:
	number_word = teens[number] if number >= 10 else ones[number]
else:
	number_word = tens[number // 10]
	if number % 10:
		number_word += " " + ones[number % 10]

last_two_digits = number % 100
if 11 <= last_two_digits <= 14:
	noun = "учебных заданий"
elif number % 10 == 1:
	noun = "учебное задание"
elif 2 <= number % 10 <= 4:
	noun = "учебных задания"
else:
	noun = "учебных заданий"

print(f"{number_word} {noun}")
