# Дано целое число N (> 0). Найти наименьшее натуральное число K, для которого сумма 1 + 2 + ... + K будет больше или равна N, и вывести найденное число K и сумму 1 + 2 + ... + K.
N = int(input("Введите число N: "))

K = 0
total = 0

while total < N:
	K += 1
	total += K

print(f"Наименьшее натуральное число K: {K}")
print(f"Сумма: {total}")
