# Дано вещественное число p, обозначающее процентную ставку. Начальная сумма равна 1000 руб. Через сколько месяцев сумма превысит 1100 руб., если каждый месяц она увеличивается на p процентов, и какая сумма будет через эти месяцы?

p = float(input("Введите процентную ставку: "))
amount = 1000.0
months = 0

while amount <= 1100:
	amount *= 1 + p / 100
	months += 1

print(f"Количество месяцев: {months}")
print(f"Сумма: {amount}")
