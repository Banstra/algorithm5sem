# Даны координаты трех точек на числовой прямой: A, B и C. Найти произведение расстояний от точки A до точки C и от точки B до точки C.
a = float(input("Введите число a: "))
b = float(input("Введите число b: "))
c = float(input("Введите число c: "))

ac = abs(c - a)
bc = abs(b - c)
print(f"Произведение расстояний: {ac * bc}")
