#Даны два ненулевых числа a и b. Найти: сумму квадратов, разность квадратов, произведение квадратов, частное квадратов.
a = float(input("Введите первое число: "))
b = float(input("Введите второе число: "))

if a == 0 or b == 0:
    print("Числа должны быть ненулевыми.")
else:
    a_sq = a * a
    b_sq = b * b

    print(f"Сумма квадратов: {a_sq + b_sq}")
    print(f"Разность квадратов: {a_sq - b_sq}")
    print(f"Произведение квадратов: {a_sq * b_sq}")
    print(f"Частное квадратов: {a_sq / b_sq}")
