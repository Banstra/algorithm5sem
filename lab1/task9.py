# Даны координаты двух точек на плоскости (x1, y1) и (x2, y2). Найти периметр и площадь прямоугольника, стороны которого параллельны осям координат и противоположные вершины которого имеют координаты (x1, y1) и (x2, y2).
x1, y1, x2, y2 = map(float, input("Введите координаты двух точек (x1 y1 x2 y2): ").split())

width = abs(x2 - x1)
height = abs(y2 - y1)

print(f"Периметр прямоугольника: {2 * (width + height)}")
print(f"Площадь прямоугольника: {width * height}")